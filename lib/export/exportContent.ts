export interface ExportSection {
  heading?: string;
  body: string;
}

export interface ExportPayload {
  filename: string;
  title: string;
  contentType: "email" | "social_media" | "story";
  sections: ExportSection[];
  metadata?: {
    platform?: string;
    wordCount?: number;
    charCount?: number;
    readingTimeMin?: number;
    tags?: string[];
  };
}

function triggerDownload(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function exportAsPlainText(payload: ExportPayload) {
  const lines: string[] = [];

  lines.push(`========================================`);
  lines.push(payload.title.toUpperCase());
  lines.push(`Generated by Ghostwriter (${payload.contentType.replace("_", " ")})`);
  if (payload.metadata?.platform) {
    lines.push(`Platform: ${payload.metadata.platform}`);
  }
  if (payload.metadata?.wordCount) {
    lines.push(`Word Count: ${payload.metadata.wordCount}`);
  }
  if (payload.metadata?.charCount) {
    lines.push(`Character Count: ${payload.metadata.charCount}`);
  }
  lines.push(`Date: ${new Date().toLocaleDateString()}`);
  lines.push(`========================================\n`);

  for (const section of payload.sections) {
    if (section.heading) {
      lines.push(`[${section.heading}]`);
    }
    lines.push(section.body);
    lines.push("");
  }

  if (payload.metadata?.tags && payload.metadata.tags.length > 0) {
    lines.push(`Tags: ${payload.metadata.tags.join(" ")}`);
  }

  const content = lines.join("\n");
  const blob = new Blob([content], { type: "text/plain;charset=utf-8" });
  triggerDownload(blob, `${payload.filename}.txt`);
}

export function exportAsMarkdown(payload: ExportPayload) {
  const lines: string[] = [];

  lines.push(`# ${payload.title}\n`);
  lines.push(`> *Generated by Ghostwriter · ${payload.contentType.replace("_", " ")} · ${new Date().toLocaleDateString()}*\n`);

  if (payload.metadata?.platform) {
    lines.push(`- **Platform:** ${payload.metadata.platform}`);
  }
  if (payload.metadata?.wordCount) {
    lines.push(`- **Word Count:** ${payload.metadata.wordCount} words`);
  }
  if (payload.metadata?.readingTimeMin) {
    lines.push(`- **Estimated Read Time:** ~${payload.metadata.readingTimeMin} min`);
  }
  if (payload.metadata?.charCount) {
    lines.push(`- **Characters:** ${payload.metadata.charCount}`);
  }
  lines.push(`\n---\n`);

  for (const section of payload.sections) {
    if (section.heading) {
      lines.push(`## ${section.heading}\n`);
    }
    lines.push(`${section.body}\n`);
  }

  if (payload.metadata?.tags && payload.metadata.tags.length > 0) {
    lines.push(`\n### Hashtags & Keywords\n`);
    lines.push(payload.metadata.tags.map(t => `\`${t}\``).join(" "));
  }

  const content = lines.join("\n");
  const blob = new Blob([content], { type: "text/markdown;charset=utf-8" });
  triggerDownload(blob, `${payload.filename}.md`);
}

