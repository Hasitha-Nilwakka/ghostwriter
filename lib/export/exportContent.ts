export function exportAsPdf(payload: ExportPayload) {
  const pageWidth = 595.28;
  const pageHeight = 841.89;
  const margin = 54;
  const lineHeight = 15;
  const titleLineHeight = 24;

  function wrapText(text: string, maxCharsPerLine = 76): string[] {
    const lines: string[] = [];
    const paragraphs = text.split("\n");
    for (const para of paragraphs) {
      if (!para.trim()) {
        lines.push("");
        continue;
      }
      const words = para.split(" ");
      let currentLine = "";
      for (const word of words) {
        if ((currentLine + " " + word).trim().length <= maxCharsPerLine) {
          currentLine = (currentLine + " " + word).trim();
        } else {
          if (currentLine) lines.push(currentLine);
          currentLine = word;
        }
      }
      if (currentLine) lines.push(currentLine);
    }
    return lines;
  }

  function escapePdf(str: string): string {
    // Strip non-ASCII or replace common unicode characters for WinAnsi / standard Helvetica
    const sanitized = str
      .replace(/[“”]/g, '"')
      .replace(/[‘’]/g, "'")
      .replace(/[—–]/g, "-")
      .replace(/…/g, "...")
      .replace(/[^\x20-\x7E\xA0-\xFF]/g, "");

    return sanitized
      .replace(/\\/g, "\\\\")
      .replace(/\(/g, "\\(")
      .replace(/\)/g, "\\)");
  }

  interface PdfLine {
    text: string;
    font: string;
    size: number;
    spacing: number;
  }

  const pages: PdfLine[][] = [];
  let currentPageLines: PdfLine[] = [];
  let currentY = pageHeight - margin;

  // Title
  const titleLines = wrapText(payload.title, 42);
  for (const tline of titleLines) {
    currentPageLines.push({ text: tline, font: "/F2", size: 16, spacing: titleLineHeight });
    currentY -= titleLineHeight;
  }

  // Subtitle/Metadata
  const subtitle = `Generated by Ghostwriter · ${payload.contentType.replace("_", " ").toUpperCase()}${
    payload.metadata?.platform ? ` (${payload.metadata.platform})` : ""
  } · ${new Date().toLocaleDateString()}`;
  currentPageLines.push({ text: subtitle, font: "/F1", size: 9, spacing: 18 });
  currentY -= 18;

  // Horizontal divider space
  currentY -= 8;

  for (const sec of payload.sections) {
    if (sec.heading) {
      if (currentY < margin + 45) {
        pages.push(currentPageLines);
        currentPageLines = [];
        currentY = pageHeight - margin;
      }
      currentPageLines.push({ text: sec.heading.toUpperCase(), font: "/F2", size: 10, spacing: 18 });
      currentY -= 18;
    }

    const bodyLines = wrapText(sec.body, 78);
    for (const line of bodyLines) {
      if (currentY < margin + 20) {
        pages.push(currentPageLines);
        currentPageLines = [];
        currentY = pageHeight - margin;
      }
      currentPageLines.push({ text: line, font: "/F1", size: 10, spacing: lineHeight });
      currentY -= lineHeight;
    }
    currentY -= 8;
  }

  if (payload.metadata?.tags && payload.metadata.tags.length > 0) {
    if (currentY < margin + 30) {
      pages.push(currentPageLines);
      currentPageLines = [];
      currentY = pageHeight - margin;
    }
    currentPageLines.push({ text: "HASHTAGS & TAGS:", font: "/F2", size: 9, spacing: 14 });
    currentY -= 14;
    const tagLines = wrapText(payload.metadata.tags.join(" "), 78);
    for (const tline of tagLines) {
      currentPageLines.push({ text: tline, font: "/F1", size: 9, spacing: 13 });
      currentY -= 13;
    }
  }

  if (currentPageLines.length > 0) {
    pages.push(currentPageLines);
  }

  // Assemble PDF 1.4 syntax
  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [];

  function addObj(content: string) {
    offsets.push(pdf.length);
    pdf += content + "\n";
  }

  // Obj 1: Catalog
  addObj("1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj");

  const pageObjIds: number[] = [];
  const contentObjIds: number[] = [];
  let nextId = 4;
  for (let i = 0; i < pages.length; i++) {
    pageObjIds.push(nextId++);
    contentObjIds.push(nextId++);
  }
  const f1Id = nextId++;
  const f2Id = nextId++;

  // Obj 2: Pages
  addObj(`2 0 obj\n<< /Type /Pages /Kids [${pageObjIds.map(id => id + " 0 R").join(" ")}] /Count ${pages.length} >>\nendobj`);

  // Obj 3: ProcSet
  addObj(`3 0 obj\n[/PDF /Text]\nendobj`);

  // Page objects and streams
  for (let i = 0; i < pages.length; i++) {
    const pageId = pageObjIds[i];
    const contentId = contentObjIds[i];

    addObj(
      `${pageId} 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${pageWidth} ${pageHeight}] /Resources << /Font << /F1 ${f1Id} 0 R /F2 ${f2Id} 0 R >> /ProcSet 3 0 R >> /Contents ${contentId} 0 R >>\nendobj`
    );

    let stream = "BT\n";
    let y = pageHeight - margin;
    for (const item of pages[i]) {
      if (!item.text) {
        y -= item.spacing;
        continue;
      }
      stream += `${item.font} ${item.size} Tf\n`;
      stream += `${margin} ${y} Td\n`;
      stream += `(${escapePdf(item.text)}) Tj\n`;
      stream += `-${margin} -${y} Td\n`;
      y -= item.spacing;
    }

    // Page footer
    stream += `/F1 8 Tf\n`;
    stream += `${margin} 28 Td\n`;
    stream += `(Generated by Ghostwriter - Page ${i + 1} of ${pages.length}) Tj\n`;
    stream += `-${margin} -28 Td\n`;
    stream += "ET\n";

    const streamBytes = new TextEncoder().encode(stream);
    addObj(`${contentId} 0 obj\n<< /Length ${streamBytes.length} >>\nstream\n${stream}endstream\nendobj`);
  }

  // Fonts
  addObj(`${f1Id} 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>\nendobj`);
  addObj(`${f2Id} 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>\nendobj`);

  const xrefOffset = pdf.length;
  const totalObjs = nextId;
  pdf += `xref\n0 ${totalObjs}\n0000000000 65535 f \n`;
  for (let i = 0; i < offsets.length; i++) {
    pdf += offsets[i].toString().padStart(10, "0") + " 00000 n \n";
  }
  pdf += `trailer\n<< /Size ${totalObjs} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;

  const blob = new Blob([pdf], { type: "application/pdf" });
  triggerDownload(blob, `${payload.filename}.pdf`);
}

function escapeHtml(str: string): string {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}
